// ═══════════════════════════════════════════════════════════════════════════
// Timer Helper
// ═══════════════════════════════════════════════════════════════════════════

/// A simple RAII timer that records duration on drop.
///
/// Usage:
/// ```ignore
/// let _timer = MetricsTimer::new("pacs.008.001.13");
/// // ... do work ...
/// // duration recorded automatically when _timer drops
/// ```
pub struct MetricsTimer {
    msg_type: String,
    start: Instant,
}

impl MetricsTimer {
    pub fn new(msg_type: &str) -> Self {
        Self { msg_type: msg_type.to_string(), start: Instant::now() }
    }
}

impl Drop for MetricsTimer {
    fn drop(&mut self) {
        record_message_duration(&self.msg_type, self.start.elapsed());
    }
}
