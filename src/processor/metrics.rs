use metrics::{counter, gauge, histogram};
use metrics_exporter_prometheus::{PrometheusBuilder, PrometheusHandle};
use std::time::Instant;

// ═══════════════════════════════════════════════════════════════════════════
// Initialization
// ═══════════════════════════════════════════════════════════════════════════

/// Install the Prometheus metrics recorder and return a handle that can
/// render the `/metrics` endpoint.
///
/// Call once at startup in `main()`, before spawning any workers:
///
/// ```ignore
/// let metrics_handle = iso20022::processor::metrics::install_metrics();
/// // ... later, in your Router:
/// .route("/metrics", get(move || ready(metrics_handle.render())))
/// ```
pub fn install_metrics() -> Result<PrometheusHandle, Box<dyn std::error::Error>> {
    let handle = PrometheusBuilder::new()
        .install_recorder()?;
    Ok(handle)
}

// ═══════════════════════════════════════════════════════════════════════════
// Message Processing
// ═══════════════════════════════════════════════════════════════════════════

/// Record a fully processed inbound message.
///
/// Labels:
/// - `msg_type`: e.g. "pacs.008.001.13"
/// - `outcome`: "success" | "permanent_failure" | "transient_failure" | "rejected" | "no_handler"
pub fn record_message_processed(msg_type: &str, outcome: &str) {
    counter!("iso20022_messages_processed_total", "msg_type" => msg_type.to_string(), "outcome" => outcome.to_string())
        .increment(1);
}

/// Record processing duration for an inbound message.
pub fn record_message_duration(msg_type: &str, duration: std::time::Duration) {
    histogram!("iso20022_message_duration_seconds", "msg_type" => msg_type.to_string())
        .record(duration.as_secs_f64());
}

/// Update the current in-flight message gauge (increment on claim, decrement on complete).
pub fn set_messages_in_flight(direction: &str, count: f64) {
    gauge!("iso20022_messages_in_flight", "direction" => direction.to_string())
        .set(count);
}

